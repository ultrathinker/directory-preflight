/**
 * A Block is a promise: it says the directory would refuse the plugin. These tests hold
 * the checker to that promise.
 *
 * Every case here is a shape the official plugin corpus ships, or a shape the live table
 * gives a different result to. Each test is named for the mistake it guards against, so
 * the same mistake cannot come back quietly.
 */

import test from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

import {
  checkGenerated, checkGeneratedDir, writeGeneratedFixture, minimalPlugin, gitIndexFixture,
  addFile, runChecker, findingsFor, generatedRoot,
} from './helpers.mjs';

const pluginJson = (extra = {}) => JSON.stringify({
  name: 'generated-tools', version: '1.0.0', description: 'A plugin generated by the test suite.',
  author: { name: 'Example Author' }, license: 'MIT', ...extra,
}, null, 2);

/** One line of output from a Git command in a fixture repository. */
function runGitLine(cwd, args) {
  return execFileSync('git', args, { cwd, encoding: 'utf8', windowsHide: true }).trim();
}

/**
 * A minimal plugin written under `plugins/demo`, so the plugin folder is a subfolder of
 * the repository. The table's path and script rows only apply there, and so do the
 * official plugins, which all sit in subfolders of the marketplace repository.
 */
const NESTED = 'plugins/demo';
function nestedPlugin(extra = {}) {
  const files = { ...minimalPlugin(), ...extra };
  return Object.fromEntries(Object.entries(files).map(([rel, content]) => [path.posix.join(NESTED, rel), content]));
}
const nestedDir = (name) => path.join(generatedRoot, name, ...NESTED.split('/'));

/**
 * A shell variable reference, assembled from pieces. This file is read by the checker it
 * tests, and a credential-shaped literal in it would be reported by the credential rules,
 * so the dollar sign never touches the name in the source.
 */
const ref = (name) => ['$', '{', name, '}'].join('');
const GH = ['GITHUB', 'TOKEN'].join('_');
const NPM = ['NPM', 'TOKEN'].join('_');

// ------------------------------------------------------- README and license file names

test('a README and a license under the names projects use are found', () => {
  // "a README of at least 40 words ... preferably named README.md": a README.rst is one, and
  // a project with two licenses ships LICENSE-MIT and LICENSE-APACHE, not a file called
  // LICENSE. Reporting either as missing was a confirmed Block on a plugin that has it.
  const bare = { ...minimalPlugin(), 'README.md': null, LICENSE: null };
  const noLicenseField = JSON.stringify({
    name: 'generated-tools', version: '1.0.0', description: 'd', author: { name: 'A' },
  });
  const readmeText = `# generated-tools\n\n${'A sentence that makes the README long enough to pass the word count rule. '.repeat(8)}\n`;
  const cases = [
    ['README.rst', 'LICENSE-MIT'],
    ['README.adoc', 'LICENSE-APACHE'],
    ['Readme', 'UNLICENSE'],
    ['README.md', 'COPYING.txt'],
    ['README.md', 'licenses/MIT.txt'],
  ];
  cases.forEach(([readme, license], index) => {
    const name = `names-${index}`;
    const files = { ...bare, '.claude-plugin/plugin.json': noLicenseField, [readme]: readmeText, [license]: 'License text.\n' };
    for (const key of Object.keys(files)) if (files[key] === null) delete files[key];
    writeGeneratedFixture(name, files);
    gitIndexFixture(name);
    const { json } = checkGeneratedDir(path.join(generatedRoot, name));
    assert.equal(findingsFor(json, 'docs/readme-missing').length, 0, `${readme}: ${JSON.stringify(json.findings, null, 2)}`);
    assert.equal(findingsFor(json, 'docs/license-missing').length, 0, `${license}: ${JSON.stringify(json.findings, null, 2)}`);
  });
});

