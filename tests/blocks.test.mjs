test('a launcher in a skill’s reference material is documentation', () => {
  // The official plugins explain MCP servers and npm commands in the reference files they
  // keep beside SKILL.md. Blocking a plugin for its own documentation is a false positive.
  writeGeneratedFixture('docs-launcher', {
    ...minimalPlugin(),
    // The command has to be somewhere a launcher reader would find it, or the test passes
    // for the wrong reason.
    'skills/helper/references/servers.md': 'Add this server:\n\n```bash\nnpx some-server --port 3000\n```\n',
  });
  gitIndexFixture('docs-launcher');
  const { json, status } = checkGenerated('docs-launcher');
  assert.equal(findingsFor(json, 'runtime/launcher-unpinned').length, 0, JSON.stringify(json.findings, null, 2));
  assert.equal(status, 0);

  // The same line in the SKILL.md itself is an instruction, and is reported as a guess.
  writeGeneratedFixture('docs-launcher-skill', {
    ...minimalPlugin(),
    'skills/helper/SKILL.md': '---\ndescription: Sets up the server for this project\n---\n\nAdd it:\n\n```bash\nnpx some-server --port 3000\n```\n',
    'skills/helper/references/servers.md': 'Add this server:\n\n```bash\nnpx some-server --port 3000\n```\n',
  });
  gitIndexFixture('docs-launcher-skill');
  const skill = checkGenerated('docs-launcher-skill');
  const hits = findingsFor(skill.json, 'runtime/launcher-unpinned');
  assert.equal(hits.length, 1, 'the SKILL.md is read, the reference file beside it is not: ' + JSON.stringify(skill.json.findings, null, 2));
  assert.equal(hits[0].path, 'skills/helper/SKILL.md');
  assert.equal(hits[0].heuristic, true);
});

