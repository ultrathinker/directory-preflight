test('every component file of this plugin is committed, and none is ignored', (t) => {
  // An export of the tree with `git archive` is a fair stand-in for a clone in every way
  // except this one: there is no repository to ask. Both the question and the answer need
  // one, so the test is skipped there rather than failing.
  if (!isRepository(projectRoot)) {
    t.skip('not a Git repository');
    return;
  }
  // The check above would still pass if a component were missing from the repository: the
  // folders it lives in simply would not be there. This test names them, from the disk, so
  // a component that an ignore rule swallows fails here instead of shipping.
  const root = projectRoot;
  const components = [];
  for (const folder of ['skills', 'commands', 'agents', 'hooks']) {
    const base = path.join(root, folder);
    // A plugin need not ship every kind of component; it does have to ship the ones it has.
    if (!fs.existsSync(base)) continue;
    const walk = (dir) => {
      for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) walk(full);
        else components.push(path.relative(root, full).split(path.sep).join('/'));
      }
    };
    walk(base);
  }
  for (const name of fs.readdirSync(path.join(root, '.claude-plugin'))) {
    components.push(`.claude-plugin/${name}`);
  }
  // The guard is only worth having if it is looking at something.
  for (const expected of ['agents/submission-checker.md', 'commands/check.md', 'skills/submission-preflight/SKILL.md']) {
    assert.equal(components.includes(expected), true, `the plugin ships ${expected}`);
  }

  const tracked = new Set(execFileSync('git', ['ls-files'], { cwd: root, encoding: 'utf8', windowsHide: true })
    .split('\n').map((line) => line.trim()).filter(Boolean));
  const missing = components.filter((rel) => !tracked.has(rel));
  assert.deepEqual(missing, [], `not committed: ${missing.join(', ')}`);

  const ignored = components.filter((rel) => {
    try {
      execFileSync('git', ['check-ignore', '-q', '--', rel], { cwd: root, windowsHide: true, stdio: 'ignore' });
      return true;
    } catch {
      return false;
    }
  });
  assert.deepEqual(ignored, [], `hidden by an ignore rule: ${ignored.join(', ')}`);
});

/** Is this folder inside a Git working tree? */
function isRepository(dir) {
  try {
    return execFileSync('git', ['rev-parse', '--is-inside-work-tree'], { cwd: dir, encoding: 'utf8', windowsHide: true, stdio: ['ignore', 'pipe', 'ignore'] }).trim() === 'true';
  } catch {
    return false;
  }
}

/** One line of output from a Git command in a fixture repository. */
function runGitLine(cwd, args) {
  return execFileSync('git', args, { cwd, encoding: 'utf8', windowsHide: true }).trim();
}