test('the documented inline-program and path cases are reported, and an HTTP hook is not', () => {
  const cases = [
    ['python3 -c "print(1)"', /inline program/],
    ['sh -c "echo hi"', /starts a shell/],
    ['bash /opt/tools/hello.sh', /not written from/],
    ['bash scripts/hello.sh', /not written from/],
    // The word itself is quoted in the message, so a variable at the root of a path is
    // named there rather than in a sentence of its own.
    ['bash $HOME/x', /the path "\$HOME\/x"/],
  ];
  for (const [command, expected] of cases) {
    const name = `hook-${command.replace(/[^a-z0-9]+/gi, '-').slice(0, 24)}`;
    writeGeneratedFixture(`${name}/plugins/alpha`, {
      '.claude-plugin/plugin.json': pluginJson(),
      LICENSE: license,
      'README.md': `# generated-tools\n\n${words(60)}\n`,
      'hooks/hooks.json': JSON.stringify({ hooks: { PreToolUse: [{ hooks: [{ type: 'command', command }] }] } }, null, 2),
    });
    gitIndexFixture(name);
    const { json } = checkGeneratedDir(path.join(generatedRoot, name, 'plugins', 'alpha'),
      ['--repo', path.join(generatedRoot, name)]);
    const hits = findingsFor(json, 'runtime/plugin-root-path');
    assert.equal(hits.length > 0, true, `${command}: ${JSON.stringify(json.findings, null, 2)}`);
    assert.match(hits[0].detail, expected, command);
  }

  writeGeneratedFixture('hook-http/plugins/alpha', {
    '.claude-plugin/plugin.json': pluginJson(),
    LICENSE: license,
    'README.md': `# generated-tools\n\n${words(60)}\n`,
    'hooks/hooks.json': JSON.stringify({
      hooks: { PostToolUse: [{ hooks: [{ type: 'http', url: 'https://hooks.example.com/session' }] }] },
    }, null, 2),
  });
  gitIndexFixture('hook-http');
  const http = checkGeneratedDir(path.join(generatedRoot, 'hook-http', 'plugins', 'alpha'),
    ['--repo', path.join(generatedRoot, 'hook-http')]);
  assert.equal(findingsFor(http.json, 'runtime/plugin-root-path').length, 0,
    'an HTTP hook has a URL, not a path');
  assert.equal(http.json.summary.byResult.block, 0, JSON.stringify(http.json.findings, null, 2));
});

