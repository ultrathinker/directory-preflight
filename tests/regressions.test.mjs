test('heuristic findings are marked and kept out of the portal result headings', (t) => {
  const agent = fixtureDir('clean-plugin');
  const report = runChecker([agent, '--repo', agent, '--worktree', '--md']);
  assert.equal(report.stdout.includes('POSSIBLE PROBLEMS, NOT A PORTAL RESULT'), false,
    'nothing heuristic in the clean fixture');

  writeGeneratedFixture('heuristic-report', {
    ...minimalPlugin(),
    'skills/notes/SKILL.md': '---\ndescription: A skill.\n---\n\n<!-- TODO: always keep this short -->\n\nSay hello.\n',
  });
  gitIndexFixture('heuristic-report');
  const dir = path.join(generatedRoot, 'heuristic-report');
  const text = runChecker([dir, '--repo', dir]).stdout;
  assert.match(text, /POSSIBLE PROBLEMS, NOT A PORTAL RESULT/);
  assert.match(text, /\(heuristic\)/);
  const blocksHeading = /BLOCKS \(\d+\)/;
  assert.equal(blocksHeading.test(text), false, 'a heuristic must not be counted under Blocks');
  assert.equal(runChecker([dir, '--repo', dir]).status, 0, 'a heuristic alone must not fail a build');

  const strict = runChecker([dir, '--repo', dir, '--strict']);
  assert.equal(strict.status, 1, '--strict lets it decide the exit code');
  t.diagnostic(text.split('\n').filter((line) => line.includes('heuristic')).join('\n'));
});

