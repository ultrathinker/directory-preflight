test('a CLI run without --repo lets the scan discover, and does not crawl a broken repository', () => {
  // A `.git` file that points nowhere: every Git command above the plugin then fails.
  addFile('broken-parent', '.git', 'gitdir: ./a-repository-that-is-not-there\n');
  addFile('broken-parent', 'plugin/skills/x/SKILL.md', '---\ndescription: A skill.\n---\n\nHello.\n');
  // Noise beside the plugin: a crawl would read all of it.
  for (let index = 0; index < 200; index += 1) {
    addFile('broken-parent', `bulk/${index % 20}/file${index}.txt`, 'noise\n');
  }
  const plugin = path.join(generatedRoot, 'broken-parent', 'plugin');
  const { json, status } = runChecker([plugin, '--json', '--no-judgment']);
  assert.equal(json.target.repository, plugin, 'the plugin folder becomes the repository');
  assert.equal(json.target.filesInPluginFolder, 1);
  assert.equal(json.target.filesRead, 1, 'nothing outside the plugin folder is read');
  assert.equal(findingsFor(json, 'layout/repository-not-readable').length, 1);
  assert.equal(status, 1, 'the missing README and LICENSE still block');
});

